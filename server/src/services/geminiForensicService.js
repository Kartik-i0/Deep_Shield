import { geminiKeyPool } from './geminiKeyPool.js';

export async function analyzeWithGemini({ prompt, base64Data, mimeType, mediaType = 'image' }) {
  const keyObj = geminiKeyPool.getNextAvailableKey();
  if (!keyObj) {
    return {
      success: false,
      error: 'No active Gemini API key configured.',
    };
  }

  const candidateModels = [
    'gemini-2.5-flash-lite',
    'gemini-3.8-flash',
    'gemini-3.1-flash-lite',
  ];

  const systemInstructions = `You are DeepShield Senior Digital Forensics Auditor.
Your mandate is to accurately differentiate between:
1. "AUTHENTIC" (Real physical world photos, smartphone captures, screenshots of software/apps/code/UI, human-made graphic designs, documents, memes, natural microphone voice, human writing).
2. "AI_GENERATED" (Media generated by generative models: Midjourney, Stable Diffusion, DALL-E, Flux, Sora, ElevenLabs TTS, or deepfake face swaps).

CRITICAL FORENSIC RULES TO PREVENT FALSE POSITIVES:
- RULE 1: Screenshots of computer screens, code editors, chat apps, websites, UI, phone screens, or documents are 100% AUTHENTIC human artifacts. NEVER classify a screenshot or document as AI-generated.
- RULE 2: Standard smartphone photos (even with compression, digital noise, lens blur, or social media compression from WhatsApp/Instagram) are AUTHENTIC.
- RULE 3: Only classify content as "AI_GENERATED" if you observe undeniable generative synthesis artifacts such as:
  * Hallucinated anatomy (melted/extra fingers, deformed irises, impossible ear geometry).
  * Diffusion plastic/waxy skin texture lacking natural pores.
  * Nonsensical gibberish pseudo-letters in background signs.
  * Visible boundary blending seams from face-swap models.
- RULE 4: Presumption of Authenticity: If there is any doubt or no clear generative artifact is found, classify as "AUTHENTIC" with deepfakeProbability < 25.

Respond strictly with a valid JSON object matching this schema with NO markdown wrapping:
{
  "verdict": "AUTHENTIC" or "AI_GENERATED",
  "deepfakeProbability": <number 0-100>,
  "confidence": "HIGH" or "VERY_HIGH",
  "reasoning": "<2-3 sentence forensic explanation of why it is authentic or AI-generated based on specific visual evidence>",
  "anomalies": ["<specific observation 1>", "<specific observation 2>"],
  "breakdown": {
    "facialConsistency": <number 0-100>,
    "lightingPhysics": <number 0-100>,
    "compressionPurity": <number 0-100>,
    "metadataIntegrity": <number 0-100>
  },
  "recommendations": ["<guidance 1>", "<guidance 2>"]
}`;

  for (const model of candidateModels) {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 60000);

    try {
      const parts = [
        { text: `${systemInstructions}\n\nTask: ${prompt}` }
      ];

      if (base64Data && mimeType) {
        parts.push({
          inlineData: {
            mimeType: mimeType,
            data: base64Data,
          }
        });
      }

      const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${keyObj.raw}`;
      const response = await fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ contents: [{ parts }] }),
        signal: controller.signal,
      });

      if (response.status === 200) {
        const data = await response.json();
        const rawText = data.candidates?.[0]?.content?.parts?.[0]?.text || '';
        
        const cleaned = rawText.replace(/```json\n?/g, '').replace(/```\n?/g, '').trim();
        const parsed = JSON.parse(cleaned);

        const rawProbability = typeof parsed.deepfakeProbability === 'number'
          ? Math.min(100, Math.max(0, parsed.deepfakeProbability))
          : (parsed.verdict === 'AI_GENERATED' ? 85 : 10);

        // Calibrated decision threshold: Must have >= 60% probability to be classified as AI_GENERATED
        const finalVerdict = rawProbability >= 60 ? 'AI_GENERATED' : 'AUTHENTIC';

        geminiKeyPool.reportSuccess(keyObj);

        return {
          success: true,
          model: model,
          keyUsedMasked: keyObj.masked,
          data: {
            ...parsed,
            verdict: finalVerdict,
            deepfakeProbability: rawProbability,
          },
        };
      } else {
        const errJson = await response.json().catch(() => ({}));
        if (response.status === 429) {
          geminiKeyPool.reportRateLimit(keyObj, errJson.error?.message);
        }
      }
    } catch (err) {
      console.warn(`[Gemini API] Request with model ${model} failed:`, err.message);
    } finally {
      clearTimeout(timeout);
    }
  }

  return {
    success: false,
    error: 'Gemini API call timed out or failed; falling back to local forensic analysis.',
  };
}
